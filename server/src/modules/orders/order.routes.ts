import express from "express";
import {
  createOrder,
  getOrderById,
  getUserOrders,
  getAllOrders,
  updateOrderStatus,
  updatePaymentStatus,
  deleteOrder,
} from "./order.controller.js";

import { restrictTo } from "../../middleware/role.middleware.js";

const orderRouter = express.Router();

/**
 * @swagger
 * tags:
 *   name: Orders
 *   description: Order management system
 */

/**
 * @swagger
 * components:
 *   schemas:
 *     OrderItem:
 *       type: object
 *       properties:
 *         productId:
 *           type: string
 *         quantity:
 *           type: number
 *         price:
 *           type: number
 *
 *     ShippingAddress:
 *       type: object
 *       properties:
 *         street:
 *           type: string
 *         city:
 *           type: string
 *         state:
 *           type: string
 *         postalCode:
 *           type: string
 *         country:
 *           type: string
 *
 *     Order:
 *       type: object
 *       properties:
 *         _id:
 *           type: string
 *         userId:
 *           type: string
 *         items:
 *           type: array
 *           items:
 *             $ref: '#/components/schemas/OrderItem'
 *         totalAmount:
 *           type: number
 *         shippingAddress:
 *           $ref: '#/components/schemas/ShippingAddress'
 *         paymentMethod:
 *           type: string
 *         paymentStatus:
 *           type: string
 *           enum: [pending, paid, failed]
 *         orderStatus:
 *           type: string
 *           enum: [pending, processing, shipped, delivered, cancelled]
 *         createdAt:
 *           type: string
 *         updatedAt:
 *           type: string
 */

////////////////////////////////////////////////////////////////////////////////
// CREATE ORDER
////////////////////////////////////////////////////////////////////////////////

/**
 * @swagger
 * /orders:
 *   post:
 *     summary: Create a new order
 *     tags: [Orders]
 *     security:
 *       - bearerAuth: []
 *     requestBody:
 *       required: true
 *       content:
 *         application/json:
 *           schema:
 *             type: object
 *             required:
 *               - addressId
 *               - paymentMethod
 *             properties:
 *               addressId:
 *                 type: string
 *               paymentMethod:
 *                 type: string
 *     responses:
 *       201:
 *         description: Order created successfully
 *         content:
 *           application/json:
 *             schema:
 *               type: object
 *               properties:
 *                 success:
 *                   type: boolean
 *                 order:
 *                   $ref: '#/components/schemas/Order'
 */
orderRouter.post("/", createOrder);

////////////////////////////////////////////////////////////////////////////////
// GET MY ORDERS
////////////////////////////////////////////////////////////////////////////////

/**
 * @swagger
 * /orders/me:
 *   get:
 *     summary: Get logged-in user's orders
 *     tags: [Orders]
 *     security:
 *       - bearerAuth: []
 *     responses:
 *       200:
 *         description: List of user orders
 *         content:
 *           application/json:
 *             schema:
 *               type: object
 *               properties:
 *                 success:
 *                   type: boolean
 *                 orders:
 *                   type: array
 *                   items:
 *                     $ref: '#/components/schemas/Order'
 */
orderRouter.get("/me", getUserOrders);

/**
 * @swagger
 * /orders:
 *   get:
 *     summary: Get all orders (Admin only)
 *     tags: [Orders]
 *     security:
 *       - bearerAuth: []
 *     responses:
 *       200:
 *         description: List of all orders
 */
orderRouter.get("/", restrictTo("admin"), getAllOrders);

////////////////////////////////////////////////////////////////////////////////
// GET ORDER BY ID (ADMIN ONLY)
////////////////////////////////////////////////////////////////////////////////

/**
 * @swagger
 * /orders/{orderId}:
 *   get:
 *     summary: Get order by ID (Admin only)
 *     tags: [Orders]
 *     security:
 *       - bearerAuth: []
 *     parameters:
 *       - in: path
 *         name: orderId
 *         required: true
 *         schema:
 *           type: string
 *     responses:
 *       200:
 *         description: Order retrieved successfully
 *         content:
 *           application/json:
 *             schema:
 *               type: object
 *               properties:
 *                 success:
 *                   type: boolean
 *                 order:
 *                   $ref: '#/components/schemas/Order'
 */
orderRouter.get("/:orderId", restrictTo("admin"), getOrderById);

////////////////////////////////////////////////////////////////////////////////
// UPDATE ORDER STATUS (ADMIN ONLY)
////////////////////////////////////////////////////////////////////////////////

/**
 * @swagger
 * /orders/{orderId}/status:
 *   patch:
 *     summary: Update order status (Admin only)
 *     tags: [Orders]
 *     security:
 *       - bearerAuth: []
 *     parameters:
 *       - in: path
 *         name: orderId
 *         required: true
 *         schema:
 *           type: string
 *     requestBody:
 *       required: true
 *       content:
 *         application/json:
 *           schema:
 *             type: object
 *             required:
 *               - orderStatus
 *             properties:
 *               orderStatus:
 *                 type: string
 *                 enum: [pending, processing, shipped, delivered, cancelled]
 *     responses:
 *       200:
 *         description: Order status updated
 */
orderRouter.patch(
  "/:orderId/status",
  restrictTo("admin"),
  updateOrderStatus
);

////////////////////////////////////////////////////////////////////////////////
// UPDATE PAYMENT STATUS (ADMIN ONLY)
////////////////////////////////////////////////////////////////////////////////

/**
 * @swagger
 * /orders/{orderId}/payment-status:
 *   patch:
 *     summary: Update payment status (Admin only)
 *     tags: [Orders]
 *     security:
 *       - bearerAuth: []
 *     parameters:
 *       - in: path
 *         name: orderId
 *         required: true
 *         schema:
 *           type: string
 *     requestBody:
 *       required: true
 *       content:
 *         application/json:
 *           schema:
 *             type: object
 *             required:
 *               - paymentStatus
 *             properties:
 *               paymentStatus:
 *                 type: string
 *                 enum: [pending, paid, failed]
 *     responses:
 *       200:
 *         description: Payment status updated
 */
orderRouter.patch(
  "/:orderId/payment-status",
  restrictTo("admin"),
  updatePaymentStatus
);

////////////////////////////////////////////////////////////////////////////////
// DELETE ORDER (ADMIN ONLY)
////////////////////////////////////////////////////////////////////////////////

/**
 * @swagger
 * /orders/{orderId}:
 *   delete:
 *     summary: Delete an order (Admin only)
 *     tags: [Orders]
 *     security:
 *       - bearerAuth: []
 *     parameters:
 *       - in: path
 *         name: orderId
 *         required: true
 *         schema:
 *           type: string
 *     responses:
 *       200:
 *         description: Order deleted successfully
 */
orderRouter.delete(
  "/:orderId",
  restrictTo("admin"),
  deleteOrder
);

export default orderRouter;